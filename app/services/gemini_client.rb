require "net/http"
require "uri"
require "json"

class GeminiClient
  BASE_URL = "https://generativelanguage.googleapis.com/v1beta/models".freeze
  DEFAULT_MODEL = "gemini-3.8-flash".freeze

  # Base error class for all Gemini-related issues
  class Error < StandardError; end

  # Specific error types that inherit from our base error
  class ConfigurationError < Error; end
  class RateLimitError < Error; end
  class TimeoutError < Error; end
  class ApiError < Error; end
  class NetworkError < Error; end

  attr_reader :api_key, :model

  def initialize(api_key: nil, model: DEFAULT_MODEL)
    @api_key = api_key || Rails.application.credentials.dig(:gemini, :api_key) ||
      ENV["GEMINI_API_KEY"]
    @model = model

    validate_configuration!
  end

  # Custom inspect to avoid leaking API keys in logs/debugging
  def inspect
    "#<#{self.class.name} model=#{model.inspect} api_key=\"[FILTERED]\">"
  end

  def generate_content(prompt, response_mime_type: "application/json")
    if prompt.blank?
      raise ArgumentError, "Prompt cannot be blank."
    end

    payload = {
      contents: [
        {
          parts: [
            { text: prompt }
          ]
        }
      ],
      generationConfig: {
        responseMimeType: response_mime_type
      }
    }

    response = send_request(payload)
    parse_response(response)
  end

  private

  def validate_configuration!
    if @api_key.blank?
      raise ConfigurationError, "Gemini API key is missing. Set it in Rails credentials (gemini.api_key) or ENV['GEMINI_API_KEY']."
    end
  end

  def send_request(payload)
    endpoint = "#{BASE_URL}/#{@model}:generateContent"
    uri = URI(endpoint)

    request = Net::HTTP::Post.new(uri)
    request["Content-Type"] = "application/json"
    request["x-goog-api-key"] = @api_key
    request.body = payload.to_json

    http = Net::HTTP.new(uri.host, uri.port)
    http.use_ssl = true
    http.open_timeout = 5
    http.read_timeout = 10

    http.request(request)
  rescue Net::OpenTimeout, Net::ReadTimeout => e
    raise TimeoutError, "Gemini request timed out: #{e.message}"
  rescue SocketError, Errno::ECONNREFUSED => e
    raise NetworkError, "Network error reaching Gemini: #{e.message}"
  end

  def parse_response(response)
    data = JSON.parse(response.body) rescue nil

    case response.code.to_i
    when 200
      raise ApiError, "Malformed Gemini response body." unless data.is_a?(Hash)

      text = data.dig("candidates", 0, "content", "parts", 0, "text")

      if text.nil?
        finish_reason = data.dig("candidates", 0, "finishReason")
        raise ApiError, "No text generated by Gemini (finish_reason: #{finish_reason || 'unknown'})."
      end

      text
    when 429
      raise RateLimitError, "Gemini rate limit exceeded (HTTP 429). Please wait a moment before trying again."
    else
      error_message = data.is_a?(Hash) ? data.dig("error", "message") : nil
      detail = error_message || response.body
      raise ApiError, "Gemini API error (HTTP #{response.code}): #{detail}"
    end
  rescue JSON::ParserError => e
    raise ApiError, "Failed to parse Gemini response: #{e.message}"
  end
end
